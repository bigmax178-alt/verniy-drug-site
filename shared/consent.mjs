// Почему так строго:
//  • ч. 1 ст. 9 152-ФЗ (в ред. ФЗ от 24.06.2025 № 156-ФЗ, действует с 01.09.2025) требует,
//    чтобы согласие оформлялось ОТДЕЛЬНО от иных информации и документов. Поэтому у нас
//    не одна галочка «согласен со всем», а несколько независимых.
//  • Согласие на распространение (публикацию) — отдельный документ по ст. 10.1 152-ФЗ,
//    его состав задан Приказом Роскомнадзора от 24.02.2021 № 18.
//  • Публикация фотографии человека — ещё и ст. 152.1 ГК РФ (охрана изображения).
//
// Версия и хэш нужны, чтобы доказать, на какую именно редакцию человек согласился
// (обязанность доказывания — на операторе, ч. 3 ст. 9 152-ФЗ). Меняете текст — поднимите version.
//
// ВАЖНО: перед публикацией тексты должен утвердить руководитель АНО, а лучше — юрист по ПДн.

import { createHash } from 'node:crypto';
import config from '../site.config.mjs';

const org = config.donate.org;
const site = config.siteUrl.replace(/\/$/, '');

export const OPERATOR = {
  name: org.name,
  shortName: `приют «${config.name}»`,
  inn: org.inn,
  ogrn: org.ogrn,
  address: config.location,
  phone: config.contacts[0].phone,
  vk: config.vk.url,
  site,
};

const hash = (text) => createHash('sha256').update(text).digest('hex').slice(0, 16);

